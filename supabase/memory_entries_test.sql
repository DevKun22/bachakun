CREATE TABLE IF NOT EXISTS public.memory_entries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message text,
  image_urls jsonb NOT NULL DEFAULT '[]'::jsonb,
  submission_id uuid NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT memory_entries_content CHECK (
    length(trim(coalesce(message, ''))) > 0 OR jsonb_array_length(image_urls) > 0
  ),
  CONSTRAINT memory_entries_message_length CHECK (length(coalesce(message, '')) <= 500),
  CONSTRAINT memory_entries_images_valid CHECK (
    jsonb_typeof(image_urls) = 'array' AND jsonb_array_length(image_urls) <= 6
  )
);
ALTER TABLE public.memory_entries ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "allow visitors to add memories" ON public.memory_entries;
CREATE POLICY "allow visitors to add memories" ON public.memory_entries
  FOR INSERT TO anon WITH CHECK (true);
GRANT USAGE ON SCHEMA public TO anon;
GRANT INSERT ON public.memory_entries TO anon;
GRANT USAGE ON SEQUENCE public.memory_entries_id_seq TO anon;
